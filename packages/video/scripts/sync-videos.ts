/**
 * Keeps the generated glue between the video registry and Remotion in step: an empty narration and
 * timing manifest for every registered video, and `src/videos/manifests.ts`, which imports them for
 * the compositions (Remotion's bundler needs static imports; this script has the list).
 *
 *   node --experimental-strip-types scripts/sync-videos.ts
 */
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { scripts } from "../src/videos/registry.ts";

const videos = resolve(dirname(fileURLToPath(import.meta.url)), "../src/videos");
const slugs = Object.keys(scripts).sort();
const ident = (slug: string) => `m_${slug.replace(/[^a-zA-Z0-9]/g, "_")}`;

for (const slug of slugs) {
  const audio = resolve(videos, `${slug}.audio.json`);
  if (!existsSync(audio))
    writeFileSync(audio, '{ "voice": null, "speed": null, "model": null, "scenes": {} }\n');
  const timing = resolve(videos, `${slug}.timing.json`);
  if (!existsSync(timing)) writeFileSync(timing, '{ "scenes": {} }\n');
}

writeFileSync(
  resolve(videos, "manifests.ts"),
  [
    "// Generated by scripts/sync-videos.ts. Do not edit.",
    'import type { AudioManifest } from "./audio.ts";',
    'import type { TimingManifest } from "./timing.ts";',
    ...slugs.flatMap((slug) => [
      `import ${ident(slug)}_audio from "./${slug}.audio.json";`,
      `import ${ident(slug)}_timing from "./${slug}.timing.json";`,
    ]),
    "",
    "export const MANIFESTS: Record<string, { audio: AudioManifest; timing: TimingManifest }> = {",
    ...slugs.map(
      (slug) =>
        `  "${slug}": { audio: ${ident(slug)}_audio as AudioManifest, timing: ${ident(slug)}_timing as TimingManifest },`,
    ),
    "};",
    "",
  ].join("\n"),
);
process.stdout.write(`${slugs.length} videos registered: ${slugs.join(", ")}\n`);
